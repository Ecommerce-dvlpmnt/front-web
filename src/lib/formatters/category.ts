/**
 * Нормализует название категории к единому украинскому языку
 */
export function formatCategoryName(name: string): string {
  if (!name) return ""
  const normalized = name.trim().toLowerCase()
  return CATEGORY_TRANSLATIONS[normalized] ?? name
}
